import { createFileRoute, useNavigate } from '@tanstack/react-router';
import { useEffect, useRef, useState } from 'react';
import { Upload, ImagePlus, ArrowRight, RotateCcw, LoaderCircle, ShieldCheck } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { createDemoAnalysis, validateFieldImage } from '@/lib/analysis-demo';
import { pageMeta } from '@/lib/page-meta';
import fieldImage from '@/assets/agrinova-fields.jpg';

const recommendedCrop = {
  name: 'Sorghum + drought-tolerant pulse blend',
  fit: '92% fit',
  water: 'Low to moderate irrigation',
  season: 'Best for next 90 days',
  image: fieldImage,
  notes: 'This zone is best suited to crops that handle heat stress and variable moisture without rapid yield loss.',
};

async function analyzeFieldImage(file: File, fileLabel: string) {
  void file;
  return createDemoAnalysis(fileLabel);
}

export const Route = createFileRoute('/analyze')({
  head: () =>
    pageMeta(
      'Upload & Analyze a Field Image',
      'Explore the AgriNova crop intelligence demo with a field image upload and a real FastAPI-backed stress analysis endpoint.',
    ),
  component: Analyze,
});

function Analyze() {
  const navigate = useNavigate();
  const input = useRef<HTMLInputElement>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const [image, setImage] = useState<string | null>(null);
  const [file, setFile] = useState<File | null>(null);
  const [name, setName] = useState('');
  const [error, setError] = useState('');
  const [state, setState] = useState<'ready' | 'analyzing' | 'done'>('ready');
  const [dragging, setDragging] = useState(false);

  useEffect(() => () => {
    if (timer.current) clearTimeout(timer.current);
  }, []);

  function choose(selected?: File) {
    if (!selected) return;

    const issue = validateFieldImage(selected);
    if (issue) {
      setError(issue);
      return;
    }

    if (timer.current) clearTimeout(timer.current);
    setError('');
    setFile(selected);
    setImage(URL.createObjectURL(selected));
    setName(selected.name);
    setState('ready');
  }

  async function analyze() {
    if (!file) return;

    setState('analyzing');
    setError('');

    try {
      const result = await analyzeFieldImage(file, file.name || 'field-image.jpg');
      const preview = await new Promise<string>((resolve, reject) => {
        const fileReader = new FileReader();
        fileReader.onload = () => resolve(String(fileReader.result ?? fieldImage));
        fileReader.onerror = () => reject(new Error('The uploaded image could not be read.'));
        fileReader.readAsDataURL(file);
      });

      if (typeof window !== 'undefined') {
        window.sessionStorage.setItem('agrinova-last-image', preview);
        window.sessionStorage.setItem('agrinova-last-image-name', name || 'Uploaded field image');
        window.sessionStorage.setItem('agrinova-analysis', JSON.stringify(result));
      }

      setState('done');
      navigate({ to: '/results' });
    } catch (caughtError) {
      const message = caughtError instanceof Error ? caughtError.message : 'The AI analysis request failed.';
      setError(message);
      setState('ready');
    }
  }

  async function sample() {
    if (timer.current) clearTimeout(timer.current);
    setError('');
    setState('analyzing');

    try {
      const sampleBlob = await fetch(fieldImage).then((response) => response.blob());
      const sampleFile = new File([sampleBlob], 'sample-field.jpg', {
        type: sampleBlob.type || 'image/jpeg',
      });

      const result = await analyzeFieldImage(sampleFile, 'sample-field.jpg');
      setFile(sampleFile);
      setImage(fieldImage);
      setName('AgriNova sample field');

      if (typeof window !== 'undefined') {
        window.sessionStorage.setItem('agrinova-last-image', fieldImage);
        window.sessionStorage.setItem('agrinova-last-image-name', 'AgriNova sample field');
        window.sessionStorage.setItem('agrinova-analysis', JSON.stringify(result));
      }

      setState('done');
      navigate({ to: '/results' });
    } catch (caughtError) {
      const message = caughtError instanceof Error ? caughtError.message : 'The sample analysis request failed.';
      setError(message);
      setState('ready');
    }
  }

  return (
    <main>
      <div className="site-width page-heading">
        <div className="eyebrow">YOUR FIRST LOOK AT CROP INTELLIGENCE</div>
        <h1>Upload. Explore. See the possibilities.</h1>
        <p className="body-copy">Try a field photo or explore our sample field to see how crop insights are generated by the AI analysis service.</p>
      </div>

      <div className="site-width upload-layout">
        <div>
          <div
            className={`upload-box ${dragging ? 'dragging' : ''}`}
            onDragOver={(event) => {
              event.preventDefault();
              setDragging(true);
            }}
            onDragLeave={() => setDragging(false)}
            onDrop={(event) => {
              event.preventDefault();
              setDragging(false);
              choose(event.dataTransfer.files[0]);
            }}
          >
            <input
              type="file"
              ref={input}
              accept="image/jpeg,image/png,image/webp"
              className="sr-only"
              aria-label="Upload field image"
              onChange={(event) => choose(event.target.files?.[0])}
            />

            {image ? (
              <>
                <img src={image} className="uploaded-preview" alt="Selected field" />
                <p className="break-all">{name}</p>
                <div className="flex flex-wrap justify-center gap-2">
                  <Button variant="outline" onClick={() => input.current?.click()} disabled={state === 'analyzing'}>
                    <RotateCcw />
                    Change image
                  </Button>
                  <Button onClick={analyze} disabled={state === 'analyzing'}>
                    {state === 'analyzing' ? (
                      <>
                        <LoaderCircle className="animate-spin" />
                        Analyzing field…
                      </>
                    ) : (
                      <>
                        Run AI Analysis
                        <ArrowRight />
                      </>
                    )}
                  </Button>
                </div>
              </>
            ) : (
              <>
                <div className="icon-tile mb-0">
                  <ImagePlus />
                </div>
                <h3>Your field. A new perspective.</h3>
                <p>
                  Drop a field image here, or select one below.
                  <br />
                  JPG, PNG, or WebP · Up to 10 MB
                </p>
                <Button onClick={() => input.current?.click()}>
                  <Upload />
                  Choose Field Image
                </Button>
                <Button variant="link" onClick={sample}>
                  Try a sample field <ArrowRight />
                </Button>
              </>
            )}

            {error && <p role="alert" className="text-destructive">{error}</p>}
          </div>

          <p className="demo-notice flex items-start gap-2">
            <ShieldCheck size={16} className="shrink-0 mt-0.5" />
            <span>
              This demo keeps the upload in-browser and returns a fixed sample summary so the product story can be explored without storing or diagnosing user imagery.
            </span>
          </p>

          {image && (
            <Button variant="link" className="px-0" onClick={() => input.current?.click()}>
              Replace image
            </Button>
          )}
        </div>

        <aside className="feature-card">
          <span className="eyebrow">RECOMMENDED CROP PROFILE</span>
          <h3>{recommendedCrop.name}</h3>
          <div className="detail-grid">
            <div>
              <small>Fit</small>
              <strong>{recommendedCrop.fit}</strong>
            </div>
            <div>
              <small>Water</small>
              <strong>{recommendedCrop.water}</strong>
            </div>
            <div>
              <small>Season</small>
              <strong>{recommendedCrop.season}</strong>
            </div>
          </div>
          <p>{recommendedCrop.notes}</p>
        </aside>
      </div>
    </main>
  );
}

function ScanPlaceholder() {
  return <ImagePlus size={30} className="mx-auto text-primary" />;
}
